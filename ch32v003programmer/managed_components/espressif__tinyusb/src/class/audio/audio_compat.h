// 5.2.2 Control Request Layout
typedef struct TU_ATTR_PACKED {
  union {
    struct TU_ATTR_PACKED {
      uint8_t recipient : 5;
      uint8_t type      : 2;
      uint8_t direction : 1;
    } bmRequestType_bit;
    uint8_t bmRequestType;
  };
  uint8_t bRequest;
  uint8_t bChannelNumber;
  uint8_t bControlSelector;
  union {
    uint8_t bInterface;
    uint8_t bEndpoint;
  };
  uint8_t bEntityID;
  uint16_t wLength;
} audio_control_request_t;

